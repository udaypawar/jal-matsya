#!/usr/bin/env node
/**
 * Full reset: removes build/dev artifacts and installed dependencies across the
 * monorepo. Keeps source, yarn.lock and .yarn/releases, so `yarn install`
 * restores the exact same versions.
 *
 *   yarn clean            # delete everything, then run `yarn install`
 *   yarn clean --dry-run  # list what would be deleted
 */
import { existsSync, readdirSync, readFileSync, rmSync } from "node:fs"
import { join, relative, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const root = resolve(fileURLToPath(import.meta.url), "../..")
const dryRun = process.argv.includes("--dry-run")

// Paths (relative to each package dir) produced by builds, dev servers and tooling.
const ARTIFACTS = [
  ".next", // Next.js build output + cache
  "out", // next export
  "dist", // library builds
  "build",
  ".turbo", // Turborepo logs / local cache
  "coverage",
  "next-env.d.ts", // regenerated by `next dev` / `next build` / `next typegen`
  "node_modules", // installed dependencies
]

// Yarn 4 state at the repo root (regenerated by `yarn install`).
const ROOT_ARTIFACTS = [".yarn/install-state.gz", ".yarn/unplugged", ".yarn/build-state.yml"]
const ARTIFACT_EXTENSIONS = [".tsbuildinfo"]

/** Resolve workspace dirs from the root package.json ("apps/*", "packages/*"). */
function workspaceDirs() {
  const { workspaces = [] } = JSON.parse(readFileSync(join(root, "package.json"), "utf8"))
  const patterns = Array.isArray(workspaces) ? workspaces : (workspaces.packages ?? [])
  return patterns.flatMap((pattern) => {
    if (!pattern.endsWith("/*")) return [join(root, pattern)]
    const parent = join(root, pattern.slice(0, -2))
    if (!existsSync(parent)) return []
    return readdirSync(parent, { withFileTypes: true })
      .filter((entry) => entry.isDirectory())
      .map((entry) => join(parent, entry.name))
  })
}

let removed = 0
for (const dir of [root, ...workspaceDirs()]) {
  const names = dir === root ? [...ARTIFACTS, ...ROOT_ARTIFACTS] : ARTIFACTS
  const targets = names.map((name) => join(dir, name)).filter((path) => existsSync(path))
  targets.push(
    ...readdirSync(dir)
      .filter((name) => ARTIFACT_EXTENSIONS.some((ext) => name.endsWith(ext)))
      .map((name) => join(dir, name))
  )
  for (const target of targets) {
    console.log(`${dryRun ? "would remove" : "removed"}  ${relative(root, target)}`)
    if (!dryRun) rmSync(target, { recursive: true, force: true })
    removed++
  }
}

if (!removed) console.log("Nothing to clean.")
else if (dryRun) console.log(`\nFound ${removed} item(s).`)
else console.log(`\nCleaned ${removed} item(s). Run \`yarn install\` to reinstall dependencies.`)
